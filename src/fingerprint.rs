use std::path::Path;

pub struct Entry<'a> {
    pub path: String,
    pub bytes: &'a str,
}

pub const FINGERPRINT_FILE: &str = "src/fingerprint.rs";

pub fn compute(entries: &[Entry<'_>]) -> String {
    let mut kept: Vec<&Entry<'_>> = entries
        .iter()
        .filter(|e| !is_fingerprint_file(&e.path))
        .collect();
    kept.sort_by(|a, b| a.path.cmp(&b.path));

    let mut framed = Vec::new();
    for entry in kept {
        framed.extend_from_slice(entry.path.as_bytes());
        framed.push(0);
        framed.extend_from_slice(entry.bytes.len().to_string().as_bytes());
        framed.push(0);
        framed.extend_from_slice(entry.bytes.as_bytes());
    }
    crate::cache::fnv1a_hex(&framed)
}

fn is_fingerprint_file(path: &str) -> bool {
    let mut want = Path::new(FINGERPRINT_FILE).components().rev();
    let mut got = Path::new(path).components().rev();
    loop {
        match (want.next(), got.next()) {
            (None, _) => return true,
            (Some(_), None) => return false,
            (Some(w), Some(g)) if w == g => {}
            _ => return false,
        }
    }
}

pub fn fingerprint_rs(value: &str) -> String {
    format!(
        "// Generated by ForgeDB (#337). DO NOT EDIT.\n\
         //\n\
         // The fingerprint of the source this package was generated from: the app's\n\
         // `core` package plus this package's own directory, manifests included, and\n\
         // this file excluded from its own input.\n\
         //\n\
         // The consumer-facing shim beside the delivered artifact carries the same\n\
         // value and refuses to load when the two disagree. It is a change detector,\n\
         // not a version and not a signature.\n\
         pub const FINGERPRINT: &str = \"{value}\";\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_fingerprint_file_is_recognised_by_components_not_by_suffix() {
        assert!(is_fingerprint_file("napi/src/fingerprint.rs"));
        assert!(is_fingerprint_file("src/fingerprint.rs"));
        assert!(!is_fingerprint_file("napi/not_src/fingerprint.rs"));
        assert!(!is_fingerprint_file("napi/src/fingerprint.rs.bak"));
        assert!(!is_fingerprint_file("napi/src/lib.rs"));
    }
}
