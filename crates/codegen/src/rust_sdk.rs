impl ForgeDbError {
    /// A transport/client-side failure (connection refused, body decode, …):
    /// `status == 0`, no server body.
    fn transport(e: reqwest::Error) -> Self {
        Self { status: 0, message: e.to_string(), body: None }
    }
}

/// A page of list results — mirrors the REST list endpoint's response envelope.
#[derive(Debug, Clone, Deserialize)]
pub struct ListResult<T> {
    pub data: Vec<T>,
    pub total: usize,
    pub limit: usize,
    pub offset: usize,
}

/// Sort direction for a list query.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SortOrder {
    Asc,
    Desc,
}

impl SortOrder {
    fn as_str(self) -> &'static str {
        match self {
            SortOrder::Asc => "asc",
            SortOrder::Desc => "desc",
        }
    }
}

/// Options for a list query. `filter` holds exact-match `?field=value` pairs
/// matched by the generated per-model filter server-side.
#[derive(Debug, Clone, Default)]
pub struct ListOptions {
    pub limit: Option<usize>,
    pub offset: Option<usize>,
    pub sort: Option<String>,
    pub order: Option<SortOrder>,
    pub filter: Vec<(String, String)>,
}

