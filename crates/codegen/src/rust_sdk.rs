            c.push_str(&format!(
                "    /// Replace a `{name}` by id (whole-record PUT). Returns `false` if the id\n\
                 \x20   /// does not exist; errors on a constraint/conflict.\n\
                 \x20   pub async fn update_{snake}(&self, id: &str, data: &{name}) -> std::result::Result<bool, ForgeDbError> {{\n\
                 \x20       let url = format!(\"{{}}/api/{kebab}/{{}}\", self.base_url, encode_segment(id));\n\
                 \x20       let response = self.http.put(&url).json(data).send().await.map_err(ForgeDbError::transport)?;\n\
                 \x20       if response.status().as_u16() == 404 {{ return Ok(false); }}\n\
                 \x20       self.assert_ok(response).await?;\n\
                 \x20       Ok(true)\n\
                 \x20   }}\n\n"
            ));

