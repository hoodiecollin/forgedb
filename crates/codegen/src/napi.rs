//! NAPI-RS language-binding generator (#52 Node / #117 Bun) — the ergonomic
//! JavaScript-runtime wrapper over the SAME generated `database.rs`, a sibling of
//! the PyO3 wrapper (`pyo3.rs`), the native FFI spine (`ffi.rs`), and the wasm
//! replica (`wasm.rs`).
//!
//! **Option A (Node + Bun unified).** Node and Bun both run Node-API, so a SINGLE
//! NAPI-RS crate → one `.node` artifact serves both (`generate node --runtime` and
//! `generate bun --runtime` emit identical code — any Node-vs-Bun difference is
//! packaging/loader glue, not a second binding). This is why there is one emitter,
//! not two.
//!
//! It emits a per-schema `#[napi]` surface: a `ForgeDb` class whose methods mirror
//! the generated `Database` CRUD **1:1**, calling the integrity wrappers
//! (`create_<m>`/`update_<m>`/`delete_<m>`) and storage reads (`get`/`row_count`/
//! `all`) by name.
//!
//! **Marshalling (design deviation, documented — mirrors the PyO3 wrapper).** The
//! design pinned `#[napi(object)]` typed row structs ("native marshalling, no
//! serialization"); v1 instead marshals rows/ids through the generated struct's
//! **own serde impl via `Env::to_js_value`/`from_js_value`** (the napi `serde-json`
//! feature — serde↔JS value, *not* a JSON string). The caller gets native JS
//! objects, and there is exactly ONE marshalling contract (the same serde the
//! WAL / broker / FFI / PyO3 paths use), so no second per-field matrix can drift.
//! Typed `#[napi(object)]` rows (per-field native marshalling + a fully-typed
//! `.d.ts` for row shapes) are a strict ergonomic follow-up, exactly like the
//! typed-field `#[pyclass]` follow-up on the Python side.
//!
//! Identity: every schema-specific surface is generated per-model (constraint 2);
//! there is **no** generic `query`/`filter`/`predicate` entry point and no
//! `match model` dispatch (constraint 1). `Env::to_js_value` is schema-agnostic
//! (like `serde_json` in the FFI / `pythonize` in PyO3). The methods are named
//! from the schema, which IS the tailoring.

use crate::{GeneratedCode, Result};
use forgedb_parser::Schema;
use proc_macro2::TokenStream;
use quote::{format_ident, quote};

use crate::rust::RustGenerator;

pub struct NapiGenerator;

impl NapiGenerator {
    /// Generate the NAPI-RS wrapper (`napi/src/lib.rs`) for a schema.
    pub fn generate(schema: &Schema) -> Result<GeneratedCode> {
        let db_methods = Self::generate_db_methods(schema);

        let tokens = quote! {
            //! Generated by ForgeDB — Node/Bun binding (NAPI-RS, #52/#117).
            //! DO NOT EDIT - This file is auto-generated.
            //!
            //! Class-2 transport glue: the ergonomic JavaScript surface over the
            //! generated `Database`. A `ForgeDb` whose methods mirror the generated
            //! CRUD 1:1. The tailored data logic lives in the generated
            //! `database.rs`; this file binds it. It invents no query API (the
            //! identity red line). Node and Bun share this ONE `.node` (Option A).
            #![allow(warnings)]

            mod database;

            use napi::bindgen_prelude::*;
            use napi::{Env, JsUnknown};
            use napi_derive::napi;
            use std::panic::{AssertUnwindSafe, catch_unwind};

            use database::Database;
            // Names the primary-key type of UUID-keyed models (`id_type_tokens`
            // emits a bare `Uuid`); integer-PK models use std types.
            use forgedb_types::Uuid;

            /// Map any engine error (`ValidationError`, `io::Error`, …) to the
            /// JS-visible `napi::Error` (thrown as a JS `Error`).
            fn to_napi_err<E: std::fmt::Display>(e: E) -> Error {
                Error::from_reason(e.to_string())
            }

            /// Convert a caught panic payload into a `napi::Error` so an engine
            /// panic (e.g. the single-writer `DirLock`) never unwinds across the
            /// Node-API boundary as a raw abort.
            fn panic_to_napi_err(payload: Box<dyn std::any::Any + Send>) -> Error {
                let msg = payload
                    .downcast_ref::<&str>()
                    .map(|s| s.to_string())
                    .or_else(|| payload.downcast_ref::<String>().cloned())
                    .unwrap_or_else(|| "engine panic".to_string());
                Error::from_reason(msg)
            }

            /// A ForgeDB database handle — one single-writer process over a data
            /// directory. Methods mirror the generated `Database` surface 1:1.
            #[napi(js_name = "ForgeDb")]
            pub struct ForgeDb {
                inner: Database,
            }

            #[napi]
            impl ForgeDb {
                /// Open (or create) the database at `root`. Holds the single-writer
                /// lock; a second writer throws rather than aborting the runtime.
                #[napi(factory)]
                pub fn open(root: String) -> Result<Self> {
                    let root = std::path::PathBuf::from(root);
                    match catch_unwind(AssertUnwindSafe(|| Database::open_at(root))) {
                        Ok(inner) => Ok(Self { inner }),
                        Err(p) => Err(panic_to_napi_err(p)),
                    }
                }

                /// Flush every column to disk (fsync on native).
                #[napi]
                pub fn commit(&mut self) -> Result<()> {
                    match catch_unwind(AssertUnwindSafe(|| self.inner.commit())) {
                        Ok(r) => r.map_err(to_napi_err),
                        Err(p) => Err(panic_to_napi_err(p)),
                    }
                }

                /// Force a WAL checkpoint (fsync columns, then truncate the WAL).
                #[napi]
                pub fn checkpoint(&mut self) -> Result<()> {
                    match catch_unwind(AssertUnwindSafe(|| self.inner.checkpoint())) {
                        Ok(()) => Ok(()),
                        Err(p) => Err(panic_to_napi_err(p)),
                    }
                }

                /// Reclaim dead (superseded/tombstoned) row versions in-process.
                /// Explicit only — never reached from a read path (constraint 4).
                #[napi]
                pub fn compact(&mut self) -> Result<()> {
                    match catch_unwind(AssertUnwindSafe(|| self.inner.compact())) {
                        Ok(()) => Ok(()),
                        Err(p) => Err(panic_to_napi_err(p)),
                    }
                }

                #(#db_methods)*
            }
        };

        let syntax_tree = syn::parse_file(&tokens.to_string()).map_err(|e| {
            crate::CodegenError::GenerationFailed(format!(
                "Failed to parse generated NAPI-RS binding: {e}"
            ))
        })?;
        let code = prettyplease::unparse(&syntax_tree);

        Ok(GeneratedCode {
            code,
            description: format!("Node/Bun binding (NAPI-RS) ({} models)", schema.models.len()),
        })
    }

    /// The identity models a binding surface is generated for — those with an
    /// `id` field or an auto-generated PK (same filter as the FFI / PyO3 spines).
    fn identity_models(schema: &Schema) -> impl Iterator<Item = &forgedb_parser::Model> {
        schema
            .models
            .iter()
            .filter(|m| m.fields.iter().any(|f| f.name == "id" || f.auto_generate))
    }

    /// The per-model CRUD methods on `ForgeDb`, mirroring the generated `Database`
    /// integrity wrappers + storage reads 1:1. Rows/ids marshal through the
    /// generated struct's serde via `Env::to_js_value`/`from_js_value` (native JS
    /// objects, one source of truth — no second per-field matrix).
    fn generate_db_methods(schema: &Schema) -> Vec<TokenStream> {
        Self::identity_models(schema)
            .map(|model| {
                let snake = RustGenerator::to_snake_case(&model.name);
                let model_ident = format_ident!("{}", model.name);
                let storage = format_ident!("{}", snake);
                let id_ty = RustGenerator::id_type_tokens(model);

                let create_fn = format_ident!("create_{}", snake);
                let update_fn = format_ident!("update_{}", snake);
                let delete_fn = format_ident!("delete_{}", snake);

                let create_m = format_ident!("create_{}", snake);
                let get_m = format_ident!("get_{}", snake);
                let all_m = format_ident!("all_{}", snake);
                let count_m = format_ident!("count_{}", snake);
                let update_m = format_ident!("update_{}", snake);
                let delete_m = format_ident!("delete_{}", snake);

                let create_doc = format!(
                    "Insert a `{}` (FK-checked + validated); returns the new id.",
                    model.name
                );
                let get_doc =
                    format!("Fetch a `{}` by id, or `null` if absent.", model.name);
                let all_doc = format!("Every live `{}`.", model.name);
                let count_doc = format!("Physical `{}` row-count watermark.", model.name);
                let update_doc = format!(
                    "Update a `{}` by id; `true` if present, `false` if absent.",
                    model.name
                );
                let delete_doc = format!(
                    "Delete a `{}` by id (referential integrity enforced); `true`/`false`.",
                    model.name
                );

                quote! {
                    #[doc = #create_doc]
                    #[napi]
                    pub fn #create_m(&mut self, env: Env, record: JsUnknown) -> Result<JsUnknown> {
                        let record: database::#model_ident =
                            env.from_js_value(record).map_err(to_napi_err)?;
                        let id = match catch_unwind(AssertUnwindSafe(|| self.inner.#create_fn(record))) {
                            Ok(r) => r.map_err(to_napi_err)?,
                            Err(p) => return Err(panic_to_napi_err(p)),
                        };
                        env.to_js_value(&id).map_err(to_napi_err)
                    }

                    #[doc = #get_doc]
                    #[napi]
                    pub fn #get_m(&self, env: Env, id: JsUnknown) -> Result<JsUnknown> {
                        let id: #id_ty = env.from_js_value(id).map_err(to_napi_err)?;
                        let opt = match catch_unwind(AssertUnwindSafe(|| self.inner.#storage.get(id))) {
                            Ok(opt) => opt,
                            Err(p) => return Err(panic_to_napi_err(p)),
                        };
                        env.to_js_value(&opt).map_err(to_napi_err)
                    }

                    #[doc = #all_doc]
                    #[napi]
                    pub fn #all_m(&self, env: Env) -> Result<JsUnknown> {
                        let rows = match catch_unwind(AssertUnwindSafe(|| self.inner.#storage.all())) {
                            Ok(rows) => rows,
                            Err(p) => return Err(panic_to_napi_err(p)),
                        };
                        env.to_js_value(&rows).map_err(to_napi_err)
                    }

                    #[doc = #count_doc]
                    #[napi]
                    pub fn #count_m(&self) -> Result<i64> {
                        match catch_unwind(AssertUnwindSafe(|| self.inner.#storage.row_count())) {
                            Ok(n) => Ok(n as i64),
                            Err(p) => Err(panic_to_napi_err(p)),
                        }
                    }

                    #[doc = #update_doc]
                    #[napi]
                    pub fn #update_m(
                        &mut self,
                        env: Env,
                        id: JsUnknown,
                        record: JsUnknown,
                    ) -> Result<bool> {
                        let id: #id_ty = env.from_js_value(id).map_err(to_napi_err)?;
                        let record: database::#model_ident =
                            env.from_js_value(record).map_err(to_napi_err)?;
                        match catch_unwind(AssertUnwindSafe(|| self.inner.#update_fn(id, record))) {
                            Ok(r) => r.map_err(to_napi_err),
                            Err(p) => Err(panic_to_napi_err(p)),
                        }
                    }

                    #[doc = #delete_doc]
                    #[napi]
                    pub fn #delete_m(&mut self, env: Env, id: JsUnknown) -> Result<bool> {
                        let id: #id_ty = env.from_js_value(id).map_err(to_napi_err)?;
                        match catch_unwind(AssertUnwindSafe(|| self.inner.#delete_fn(id))) {
                            Ok(r) => r.map_err(to_napi_err),
                            Err(p) => Err(panic_to_napi_err(p)),
                        }
                    }
                }
            })
            .collect()
    }

    /// The NAPI-RS crate's `Cargo.toml`. User-editable config — written only when
    /// absent, mirroring the FFI / PyO3 / wasm scaffolds. A `cdylib` (the `.node`
    /// addon `require()`d by both Node and Bun); `napi`'s `serde-json` feature
    /// drives the `Env::to_js_value`/`from_js_value` marshalling; `panic = "unwind"`
    /// is load-bearing (the methods `catch_unwind` engine panics).
    pub fn cargo_toml_scaffold(crate_name: &str) -> String {
        format!(
            r#"[package]
name = "{crate_name}"
version = "0.1.0"
edition = "2024"

[lib]
# cdylib: the Node-API addon (`.node`) both Node and Bun load (Option A).
name = "forgedb"
crate-type = ["cdylib"]

[dependencies]
forgedb-storage = "0.2"
forgedb-types = "0.2"
forgedb-changefeed = "0.2"
forgedb-wal = "0.2"
forgedb-compaction = "0.1"
forgedb-txn = "0.1"
forgedb-coordinator = "0.1"
forgedb-query-params = "0.1"
forgedb-auth = "0.1"
regex = "1"
rust_decimal = {{ version = "1", features = ["serde-with-str"] }}
serde = {{ version = "1", features = ["derive"] }}
serde_json = "1"
utoipa = {{ version = "5", features = ["uuid"] }}
napi = {{ version = "2", default-features = false, features = ["napi8", "serde-json"] }}
napi-derive = "2"

[build-dependencies]
napi-build = "2"

[profile.release]
# Load-bearing: the Node-API entry points catch_unwind engine panics, so the
# release profile must unwind (not abort) for that boundary to hold.
panic = "unwind"
"#
        )
    }

    /// The NAPI-RS `build.rs` (schema-invariant). `napi_build::setup()` wires the
    /// platform linker args (incl. macOS `-undefined dynamic_lookup` so the
    /// `.node` resolves Node-API symbols at load time), so a plain `cargo build`
    /// links standalone — the compile-test path.
    pub fn build_rs_scaffold() -> &'static str {
        "// Generated by ForgeDB — NAPI-RS build script (schema-invariant).\n\
         fn main() {\n    \
         napi_build::setup();\n\
         }\n"
    }

    /// The `package.json` for the generated binding — makes `@napi-rs/cli` the
    /// blessed build path (`napi build` → the `.node` + a generated `index.js`
    /// loader + `index.d.ts`). User-editable — written only when absent.
    pub fn package_json_scaffold() -> &'static str {
        r#"{
  "name": "forgedb",
  "version": "0.1.0",
  "description": "Generated ForgeDB Node/Bun binding (NAPI-RS)",
  "main": "index.js",
  "types": "index.d.ts",
  "napi": {
    "name": "forgedb"
  },
  "scripts": {
    "build": "napi build --platform --release",
    "build:debug": "napi build --platform"
  },
  "devDependencies": {
    "@napi-rs/cli": "^2.18.0"
  }
}
"#
    }
}
