use std::path::Path;

use crate::GenConfig;

pub struct CorePackage;

impl CorePackage {
    pub fn cargo_toml(crate_name: &str, config: &GenConfig) -> String {
        let utoipa = if config.needs_utoipa() {
            "utoipa = { version = \"5\", features = [\"uuid\"] }\n"
        } else {
            ""
        };

        format!(
            r#"# Generated by ForgeDB. Do not edit — rewritten in full on every generate.
#
# NOTHING IN THE CACHE IS USER-EDITABLE. The scaffolds in your output directory
# are written only when absent, because they are yours; this file is ForgeDB's,
# and carrying a stale copy forward is how a CLI upgrade that bumps a substrate
# pin fails to reach an existing project.
[package]
name = "{crate_name}"
version = "0.1.0"
edition = "2024"

[lib]
# An rlib: every wrapper in this app links it as a plain Rust dependency, which
# is what makes their substrate types UNIFY rather than merely happen to match.
crate-type = ["rlib"]

[dependencies]
forgedb-storage = "0.3"
forgedb-types = "0.3"
forgedb-changefeed = "0.2"
forgedb-wal = "0.2"
forgedb-compaction = "0.1"
forgedb-txn = "0.1"
regex = "1"
rust_decimal = {{ version = "1", features = ["serde-with-str"] }}
serde = {{ version = "1", features = ["derive"] }}
serde_json = "1"
{utoipa}
# The multi-process write coordinator is native-only (Unix sockets + fs2); the
# browser replica cfg-gates its entire surface out, so it must not be a
# dependency on wasm32 or `core` stops building for the replica.
[target.'cfg(not(target_arch = "wasm32"))'.dependencies]
forgedb-coordinator = "0.2"
"#
        )
    }

    pub const LIB_RS: &'static str = "src/lib.rs";

    pub const CARGO_TOML: &'static str = "Cargo.toml";

    pub fn files(crate_name: &str, config: &GenConfig, lib_rs: &str) -> Vec<(&'static str, String)> {
        vec![
            (Self::CARGO_TOML, Self::cargo_toml(crate_name, config)),
            (Self::LIB_RS, lib_rs.to_string()),
        ]
    }

    pub fn dep_line(package: &str, path: &Path) -> String {
        format!(
            "forgedb_core = {{ package = {}, path = {} }}",
            toml_string(package),
            toml_string(&path.display().to_string()),
        )
    }
}

fn toml_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cfg(web: bool) -> GenConfig {
        GenConfig {
            web,
            ..GenConfig::DEFAULT
        }
    }

    #[test]
    fn utoipa_is_present_only_when_the_app_declares_a_web_surface() {
        let with = CorePackage::cargo_toml("app-core", &cfg(true));
        let without = CorePackage::cargo_toml("app-core", &cfg(false));

        assert!(with.contains("utoipa"), "{with}");
        assert!(
            !without.contains("utoipa"),
            "utoipa must not be pinned when nothing derives ToSchema:\n{without}"
        );
    }

    #[test]
    fn the_pin_and_the_import_agree_for_every_config() {
        let src = "User {\n  id: +uuid\n  email: &string\n  name: string\n}\n";
        let schema = forgedb_parser::Parser::new(src)
            .and_then(|mut p| p.parse())
            .expect("fixture schema parses");

        for web in [true, false] {
            let config = cfg(web);
            let manifest = CorePackage::cargo_toml("app-core", &config);
            let source = crate::RustGenerator::generate_with_config(&schema, 1, config)
                .expect("database.rs")
                .code;

            assert_eq!(
                manifest.contains("\nutoipa = "),
                source.contains("use utoipa :: ToSchema")
                    || source.contains("use utoipa::ToSchema"),
                "core/Cargo.toml and core/src/lib.rs disagree about utoipa at \
                 web={web} — the emitted crate does not compile.\n{manifest}"
            );
        }
    }

    #[test]
    fn the_dep_line_renames_the_package_and_parses() {
        let line = CorePackage::dep_line("demo-core", Path::new("generated/core"));
        let parsed: toml::Value = toml::from_str(&line).expect("the dep line must be valid TOML");
        let dep = &parsed["forgedb_core"];

        assert_eq!(dep["package"].as_str(), Some("demo-core"));
        assert_eq!(dep["path"].as_str(), Some("generated/core"));
        assert!(
            dep.get("version").is_none(),
            "a version requirement would give the consumer a pin to go stale: {line}"
        );
    }

    #[test]
    fn the_dep_line_escapes_its_path() {
        let line = CorePackage::dep_line("demo-core", Path::new("gen\"er\\ated/core"));
        let parsed: toml::Value = toml::from_str(&line).expect("an escaped path is still TOML");
        assert_eq!(
            parsed["forgedb_core"]["path"].as_str(),
            Some("gen\"er\\ated/core")
        );
    }

    #[test]
    fn files_enumerates_the_whole_package() {
        for web in [true, false] {
            let config = cfg(web);
            let files = CorePackage::files("demo-core", &config, "// the database\n");

            assert_eq!(files.len(), 2, "a core package is exactly two files: {files:?}");
            let names: Vec<&str> = files.iter().map(|(n, _)| *n).collect();
            assert_eq!(names, vec!["Cargo.toml", "src/lib.rs"]);

            assert_eq!(files[0].1, CorePackage::cargo_toml("demo-core", &config));
            assert_eq!(files[1].1, "// the database\n");
        }
    }

    #[test]
    fn no_profile_table_is_emitted() {
        for web in [true, false] {
            let manifest = CorePackage::cargo_toml("app-core", &cfg(web));
            assert!(!manifest.contains("[profile"), "{manifest}");
        }
    }

    #[test]
    fn the_coordinator_is_target_gated() {
        let manifest = CorePackage::cargo_toml("app-core", &cfg(false));
        let gate = manifest
            .find("[target.'cfg(not(target_arch = \"wasm32\"))'.dependencies]")
            .expect("no target gate");
        let coordinator = manifest.find("forgedb-coordinator").expect("no coordinator");
        assert!(
            coordinator > gate,
            "forgedb-coordinator must sit under the wasm32 gate:\n{manifest}"
        );
    }

    #[test]
    fn the_manifest_parses_as_toml() {
        for web in [true, false] {
            let manifest = CorePackage::cargo_toml("app-core", &cfg(web));
            toml::from_str::<toml::Value>(&manifest)
                .unwrap_or_else(|e| panic!("core manifest is not valid TOML: {e}\n{manifest}"));
        }
    }
}
