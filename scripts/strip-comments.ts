#!/usr/bin/env bun

import { readFileSync, writeFileSync } from "node:fs";

const HELP = `
strip-comments — enforce the "no comments in ForgeDB's own source" rule (#488).

  bun scripts/strip-comments.ts --check          exit 1 if any disallowed comment exists
  bun scripts/strip-comments.ts --write [paths]  rewrite files in place
  bun scripts/strip-comments.ts --stats [paths]  report what would be removed
  bun scripts/strip-comments.ts --self-test      run the lexer fixtures

THE RULE
  ForgeDB's own source carries no comments. Code is read by reading it; prose in a source
  file drifts, and it sits in a coding agent's grep path where a stale line is read as
  authoritative and steers a whole session wrong.

  User-facing documentation belongs on the website, never in a source file.

THE ONE EXCEPTION
  Bugfix commentary whose loss would likely cause a regression, written as:

      // REGRESSION(#486): <what the defect was and why this assertion shape catches it>

  It lives with the test that covers the defect, not at the defect site. The marker is
  what makes the exception auditable: 'grep -rn "REGRESSION(#" ' lists every one.

WHAT IS NOT OURS TO EDIT
  .pm-playbook/ is vendored doctrine, and .github/workflows/release.yml is GENERATED by
  cargo-dist, which self-checks it: 'dist plan' fails with "run 'dist init' to update the
  file" the moment a byte differs. Stripping its comments breaks the release pipeline.
  Both are skipped.

WHY A LEXER AND NOT A REGEX
  A regex cannot tell '//' in code from '//' inside a string. This repo is a code
  generator: its sources are full of raw strings holding Rust that itself contains '///'.
  Those must survive untouched. The lexers below track string, raw-string, char and
  lifetime state so only real comment tokens are removed.
`;

type Kind = "rust" | "ts" | "hash";

interface Cut {
  start: number;
  end: number;
  inline: boolean;
}

const REGRESSION = /^\s*(?:\/\/|#)\s*REGRESSION\(#\d+\):/;

const GENERATED_MARKER = /(code generated|generated by forgedb|do not edit|auto-generated)/i;

const DIRECTIVE =
  /^\s*(?:\/\/(?:export|go:[a-z]+|nolint|#\s*sourceMappingURL|\/\s*<reference|\s*@ts-|\s*eslint|\s*prettier-ignore|\s*biome-ignore|\s*deno-lint)|#\s*(?:!|cgo|include|define|ifndef|ifdef|endif|pragma))/;

function isIdent(c: string | undefined): boolean {
  return c !== undefined && /[A-Za-z0-9_]/.test(c);
}

function lineStartsAt(src: string, i: number): boolean {
  for (let j = i - 1; j >= 0; j--) {
    const c = src[j]!;
    if (c === "\n") return true;
    if (c !== " " && c !== "\t") return false;
  }
  return true;
}

function scanRust(src: string): Cut[] {
  const cuts: Cut[] = [];
  const n = src.length;
  let i = 0;
  let inRegression = false;
  while (i < n) {
    const c = src[i]!;
    const d = src[i + 1];
    if (inRegression && !/\s/.test(c) && !(c === "/" && d === "/")) inRegression = false;

    if (c === '"') {
      i++;
      while (i < n) {
        if (src[i] === "\\") { i += 2; continue; }
        if (src[i] === '"') { i++; break; }
        i++;
      }
      continue;
    }

    if ((c === "r" || c === "b") && !isIdent(src[i - 1])) {
      let p = i;
      if (c === "b" && src[p + 1] === "r") p += 2;
      else if (c === "b") p += 1;
      else p += 1;
      if (c === "b" && src[i + 1] !== "r" && src[i + 1] !== '"') { i++; continue; }
      let hashes = 0;
      while (src[p] === "#") { hashes++; p++; }
      if (src[p] === '"') {
        const close = '"' + "#".repeat(hashes);
        const at = src.indexOf(close, p + 1);
        i = at === -1 ? n : at + close.length;
        continue;
      }
      i++;
      continue;
    }

    if (c === "'") {
      if (src[i + 1] === "\\") {
        i += 2;
        while (i < n && src[i] !== "'") i++;
        i++;
        continue;
      }
      const oneCharEnd = /[\uD800-\uDBFF]/.test(src[i + 1] ?? "") ? i + 3 : i + 2;
      if (src[oneCharEnd] === "'") { i = oneCharEnd + 1; continue; }
      i++;
      continue;
    }

    if (c === "/" && d === "/") {
      const start = i;
      while (i < n && src[i] !== "\n") i++;
      const text = src.slice(start, i);
      if (REGRESSION.test(text)) {
        inRegression = true;
      } else if (!inRegression && !DIRECTIVE.test(text)) {
        cuts.push({ start, end: i, inline: !lineStartsAt(src, start) });
      }
      continue;
    }

    if (c === "/" && d === "*") {
      const start = i;
      let depth = 0;
      while (i < n) {
        if (src[i] === "/" && src[i + 1] === "*") { depth++; i += 2; continue; }
        if (src[i] === "*" && src[i + 1] === "/") {
          depth--; i += 2;
          if (depth === 0) break;
          continue;
        }
        i++;
      }
      cuts.push({ start, end: i, inline: !lineStartsAt(src, start) });
      continue;
    }

    i++;
  }
  return cuts;
}


function embeddedRustCuts(src: string): Cut[] {
  const cuts: Cut[] = [];
  const n = src.length;
  let i = 0;
  while (i < n) {
    const c = src[i]!;
    if (c === "r" && !isIdent(src[i - 1])) {
      let p = i + 1;
      let hashes = 0;
      while (src[p] === "#") { hashes++; p++; }
      if (src[p] === '"') {
        const close = '"' + "#".repeat(hashes);
        const at = src.indexOf(close, p + 1);
        const end = at === -1 ? n : at;
        const body = src.slice(p + 1, end);
        if (/^\s*(pub\s+)?fn\s+\w+\s*[(<]/m.test(body) || /^\s*use\s+[\w:]+\s*(::\{|;)/m.test(body)) {
          let off = p + 1;
          for (const line of body.split("\n")) {
            if (
              /^\s*(\/\/\/|\/\/!|\/\/)/.test(line) &&
              !REGRESSION.test(line) &&
              !DIRECTIVE.test(line) &&
              !GENERATED_MARKER.test(line)
            ) {
              cuts.push({ start: off, end: off + line.length, inline: false });
            }
            off += line.length + 1;
          }
        }
        i = at === -1 ? n : at + close.length;
        continue;
      }
    }
    if (c === '"') {
      i++;
      while (i < n) {
        if (src[i] === "\\") { i += 2; continue; }
        if (src[i] === '"') break;
        i++;
      }
      i++;
      continue;
    }
    if (c === "/" && src[i + 1] === "/") { while (i < n && src[i] !== "\n") i++; continue; }
    i++;
  }
  return cuts;
}

function scanTs(src: string): Cut[] {
  const cuts: Cut[] = [];
  const n = src.length;
  let i = 0;
  let prevSignificant = "";
  let inRegression = false;
  while (i < n) {
    const c = src[i]!;
    const d = src[i + 1];
    if (inRegression && !/\s/.test(c) && !(c === "/" && d === "/")) inRegression = false;

    if (c === '"' || c === "'" || c === "`") {
      const quote = c;
      i++;
      while (i < n) {
        if (src[i] === "\\") { i += 2; continue; }
        if (quote === "`" && src[i] === "$" && src[i + 1] === "{") {
          let depth = 1;
          i += 2;
          while (i < n && depth > 0) {
            if (src[i] === "{") depth++;
            else if (src[i] === "}") depth--;
            i++;
          }
          continue;
        }
        if (src[i] === quote) { i++; break; }
        i++;
      }
      prevSignificant = "lit";
      continue;
    }

    if (c === "/" && d === "/") {
      const start = i;
      while (i < n && src[i] !== "\n") i++;
      const text = src.slice(start, i);
      if (REGRESSION.test(text)) {
        inRegression = true;
      } else if (!inRegression && !DIRECTIVE.test(text)) {
        cuts.push({ start, end: i, inline: !lineStartsAt(src, start) });
      }
      continue;
    }

    if (c === "/" && d === "*") {
      const start = i;
      const at = src.indexOf("*/", i + 2);
      i = at === -1 ? n : at + 2;
      cuts.push({ start, end: i, inline: !lineStartsAt(src, start) });
      continue;
    }

    if (c === "/" && prevSignificant !== "operand") {
      i++;
      while (i < n) {
        if (src[i] === "\\") { i += 2; continue; }
        if (src[i] === "[") { while (i < n && src[i] !== "]") { if (src[i] === "\\") i++; i++; } }
        if (src[i] === "/") { i++; break; }
        if (src[i] === "\n") break;
        i++;
      }
      prevSignificant = "operand";
      continue;
    }

    if (!/\s/.test(c)) {
      prevSignificant = /[A-Za-z0-9_$)\]]/.test(c) ? "operand" : "op";
    }
    i++;
  }
  return cuts;
}

function scanHash(src: string, yaml: boolean): Cut[] {
  const cuts: Cut[] = [];
  const lines = src.split("\n");
  let off = 0;
  let inRegression = false;
  let blockIndent: number | null = null;
  for (const line of lines) {
    if (yaml) {
      const indent = line.length - line.trimStart().length;
      if (blockIndent !== null) {
        if (line.trim() === "" || indent > blockIndent) { off += line.length + 1; continue; }
        blockIndent = null;
      }
      if (/[|>][+-]?\d*\s*$/.test(line.replace(/\s+#.*$/, ""))) {
        blockIndent = indent;
        off += line.length + 1;
        continue;
      }
    }
    if (inRegression && !/^\s*(#|$)/.test(line)) inRegression = false;
    let i = 0;
    let inStr: string | null = null;
    while (i < line.length) {
      const c = line[i]!;
      if (inStr) {
        if (c === "\\") { i += 2; continue; }
        if (c === inStr) inStr = null;
        i++;
        continue;
      }
      if (c === '"' || c === "'") { inStr = c; i++; continue; }
      if (c === "#") {
        const seg = line.slice(i);
        if (REGRESSION.test(seg)) {
          inRegression = true;
        } else if (!inRegression && !DIRECTIVE.test(seg)) {
          cuts.push({ start: off + i, end: off + line.length, inline: !/^\s*$/.test(line.slice(0, i)) });
        }
        break;
      }
      i++;
    }
    off += line.length + 1;
  }
  return cuts;
}

function scan(src: string, kind: Kind, yaml = false): Cut[] {
  if (kind === "rust") {
    const all = [...scanRust(src), ...embeddedRustCuts(src)];
    return all.sort((a, b) => a.start - b.start);
  }
  if (kind === "ts") return scanTs(src);
  return scanHash(src, yaml);
}

function strip(src: string, kind: Kind, yaml = false): string {
  const cuts = scan(src, kind, yaml);
  if (cuts.length === 0) return src;

  let out = "";
  let at = 0;
  for (const cut of cuts) {
    out += src.slice(at, cut.start);
    if (cut.inline) {
      const after = src.slice(cut.end);
      const nl = after.indexOf("\n");
      const restOfLine = after.slice(0, nl === -1 ? after.length : nl);
      const prevChar = out.slice(-1);
      const nextChar = restOfLine.slice(0, 1);
      const needsSpace =
        restOfLine.trim() !== "" &&
        prevChar !== "" && !/\s/.test(prevChar) &&
        nextChar !== "" && !/\s/.test(nextChar);
      if (needsSpace) out += " ";
    }
    at = cut.end;
  }
  out += src.slice(at);

  const kept = new Set<number>();
  const origLines = src.split("\n");
  const outLines = out.split("\n");
  for (let i = 0; i < outLines.length; i++) {
    const wasBlank = (origLines[i] ?? "").trim() === "";
    if (outLines[i]!.trim() === "" && !wasBlank) continue;
    kept.add(i);
  }

  const result: string[] = [];
  let blankRun = 0;
  for (let i = 0; i < outLines.length; i++) {
    if (!kept.has(i)) continue;
    const line = outLines[i]!.replace(/[ \t]+$/, "");
    if (line === "") {
      blankRun++;
      if (blankRun > 1) continue;
    } else {
      blankRun = 0;
    }
    result.push(line);
  }

  let text = result.join("\n");
  text = text.replace(/^\n+/, "");
  text = text.replace(/\n+$/, "\n");
  if (!text.endsWith("\n")) text += "\n";
  return text;
}

const RUST = /\.rs$/;
const TS = /\.(ts|tsx|mts|cts)$/;
const HASH = /(\.toml|\.ya?ml)$|(^|\/)Makefile$/;

function kindOf(path: string): Kind | null {
  if (RUST.test(path)) return "rust";
  if (TS.test(path)) return "ts";
  if (HASH.test(path)) return "hash";
  return null;
}

const SKIP = [
  ".pm-playbook/",
  ".github/workflows/release.yml",
  "node_modules/",
  "target/",
  "generated/",
  ".worktrees/",
  ".devbox/",
  "apps/inspector/src-tauri/target/",
];

function tracked(): string[] {
  const out = Bun.spawnSync(["git", "ls-files"], { cwd: process.cwd() });
  return new TextDecoder()
    .decode(out.stdout)
    .split("\n")
    .filter((p) => p !== "")
    .filter((p) => !SKIP.some((s) => p.startsWith(s) || p.includes("/" + s)));
}

function selfTest(): number {
  const cases: Array<[string, Kind, string]> = [
    ['let s = "// not a comment";\n', "rust", 'let s = "// not a comment";\n'],
    ['let s = r#"/// generated doc"#;\n', "rust", 'let s = r#"/// generated doc"#;\n'],
    [
      'const D: &str = r##"use x;\n/// doc\nfn main() {}\n"##;\n',
      "rust",
      'const D: &str = r##"use x;\nfn main() {}\n"##;\n',
    ],
    [
      'const S: &str = r#"User {\n// forge comment stays\n}"#;\n',
      "rust",
      'const S: &str = r#"User {\n// forge comment stays\n}"#;\n',
    ],
    [
      'const J: &str = r#"\nmod = await import(x);\n// js comment stays\n"#;\n',
      "rust",
      'const J: &str = r#"\nmod = await import(x);\n// js comment stays\n"#;\n',
    ],
    [
      'const D: &str = r##"use x;\n// Generated by ForgeDB - DO NOT EDIT\n/// gone\nfn main() {}\n"##;\n',
      "rust",
      'const D: &str = r##"use x;\n// Generated by ForgeDB - DO NOT EDIT\nfn main() {}\n"##;\n',
    ],
    ['let u = "https://example.com";\n', "rust", 'let u = "https://example.com";\n'],
    ["let a: &'static str = x;\n", "rust", "let a: &'static str = x;\n"],
    ["let c = '/';\n", "rust", "let c = '/';\n"],
    ["let c = '\\'';\n", "rust", "let c = '\\'';\n"],
    ["fn f() {}\n// gone\nfn g() {}\n", "rust", "fn f() {}\nfn g() {}\n"],
    ["let x = 5; // trailing\n", "rust", "let x = 5;\n"],
    ["/// doc\nfn f() {}\n", "rust", "fn f() {}\n"],
    ["//! inner\nfn f() {}\n", "rust", "fn f() {}\n"],
    ["/* /* nested */ */\nfn f() {}\n", "rust", "fn f() {}\n"],
    ["foo(/* x */ y);\n", "rust", "foo( y);\n"],
    ["let z = a/*x*/b;\n", "rust", "let z = a b;\n"],
    [
      "// REGRESSION(#486): kept\nfn f() {}\n",
      "rust",
      "// REGRESSION(#486): kept\nfn f() {}\n",
    ],
    [
      "// REGRESSION(#486): one\n// two\n// three\nfn f() {}\n",
      "rust",
      "// REGRESSION(#486): one\n// two\n// three\nfn f() {}\n",
    ],
    [
      "// REGRESSION(#1): a\nfn f() {}\n// unrelated\nfn g() {}\n",
      "rust",
      "// REGRESSION(#1): a\nfn f() {}\nfn g() {}\n",
    ],
    ['const S = "// no";\n', "ts", 'const S = "// no";\n'],
    ["//export Foo\nfunc Foo() {}\n", "rust", "//export Foo\nfunc Foo() {}\n"],
    ["//go:build linux\nfn f() {}\n", "rust", "//go:build linux\nfn f() {}\n"],
    ["// @ts-ignore\nconst a = 1;\n", "ts", "// @ts-ignore\nconst a = 1;\n"],
    ["// eslint-disable-next-line\nconst a = 1;\n", "ts", "// eslint-disable-next-line\nconst a = 1;\n"],
    ["#!/usr/bin/env bun\nx = 1\n", "hash", "#!/usr/bin/env bun\nx = 1\n"],
    ["const R = /a\\/\\/b/;\n", "ts", "const R = /a\\/\\/b/;\n"],
    ["const T = `x // y`;\n", "ts", "const T = `x // y`;\n"],
    ["/** doc */\nexport const a = 1;\n", "ts", "export const a = 1;\n"],
    ['key = "value" # note\n', "hash", 'key = "value"\n'],
    ["a: b # gone\nrun: |\n  echo '#390 stays'\n  # and so does this\nc: d\n", "hash", "a: b\nrun: |\n  echo '#390 stays'\n  # and so does this\nc: d\n"],
    ['key = "# not a comment"\n', "hash", 'key = "# not a comment"\n'],
  ];
  let failed = 0;
  for (const [input, kind, want] of cases) {
    const got = strip(input, kind, kind === "hash" && input.includes(": |"));
    if (got !== want) {
      failed++;
      console.error(`FAIL [${kind}]\n  in:   ${JSON.stringify(input)}\n  want: ${JSON.stringify(want)}\n  got:  ${JSON.stringify(got)}`);
    }
  }
  console.log(failed === 0 ? `self-test: ${cases.length} passed` : `self-test: ${failed} FAILED`);
  return failed === 0 ? 0 : 1;
}

function main(): number {
  const argv = process.argv.slice(2);
  if (argv.length === 0 || argv.includes("--help")) {
    console.log(HELP);
    return argv.length === 0 ? 2 : 0;
  }
  if (argv.includes("--self-test")) return selfTest();

  const mode = argv.includes("--write") ? "write" : argv.includes("--check") ? "check" : "stats";
  const explicit = argv.filter((a) => !a.startsWith("--"));
  const files = (explicit.length > 0 ? explicit : tracked()).filter((p) => kindOf(p) !== null);

  let changed = 0;
  let removedLines = 0;
  const offenders: Array<[string, number]> = [];

  for (const path of files) {
    const kind = kindOf(path)!;
    let src: string;
    try {
      src = readFileSync(path, "utf8");
    } catch {
      continue;
    }
    const isYaml = /\.ya?ml$/.test(path);
    const out = strip(src, kind, isYaml);
    if (out === src) continue;
    changed++;
    const delta = src.split("\n").length - out.split("\n").length;
    removedLines += delta;
    offenders.push([path, scan(src, kind, isYaml).length]);
    if (mode === "write") writeFileSync(path, out);
  }

  if (mode === "check") {
    if (offenders.length === 0) {
      console.log(`no comments in ${files.length} tracked source files`);
      return 0;
    }
    console.error(`${offenders.length} file(s) carry disallowed comments:\n`);
    for (const [path, count] of offenders.slice(0, 40)) {
      console.error(`  ${path}  (${count} comment${count === 1 ? "" : "s"})`);
    }
    if (offenders.length > 40) console.error(`  … and ${offenders.length - 40} more`);
    console.error(`\nForgeDB's own source carries no comments (#488). Delete them, or — only for`);
    console.error(`bugfix commentary that prevents a regression, beside its test — write:`);
    console.error(`\n    // REGRESSION(#<issue>): <what the defect was>\n`);
    console.error(`Fix: bun scripts/strip-comments.ts --write`);
    return 1;
  }

  console.log(`${mode}: ${changed} file(s) of ${files.length}, ~${removedLines} line(s) removed`);
  return 0;
}

process.exit(main());
